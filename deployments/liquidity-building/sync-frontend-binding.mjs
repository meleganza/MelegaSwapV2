#!/usr/bin/env node
/**
 * Sync frontend canonical binding from chain-56/deployed-addresses.v1.json.
 * Refuses to write non-null addresses unless mainnetDeployExecuted === true
 * and every core address is a non-zero hex address.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '../..')
const ARTIFACT = path.join(__dirname, 'chain-56/deployed-addresses.v1.json')
const TARGET = path.join(ROOT, 'apps/web/src/config/constants/liquidityBuildingDeployment.ts')

function isAddr(v) {
  return typeof v === 'string' && /^0x[a-fA-F0-9]{40}$/.test(v) && !/^0x0{40}$/i.test(v)
}

const doc = JSON.parse(fs.readFileSync(ARTIFACT, 'utf8'))
const a = doc.addresses || {}

if (doc.mainnetDeployExecuted) {
  for (const key of ['lbFactory', 'lbAuthorizer', 'lbFeeSink']) {
    if (!isAddr(a[key])) {
      console.error(`Refusing sync: mainnetDeployExecuted but ${key} invalid`)
      process.exit(1)
    }
  }
} else {
  for (const key of ['lbFactory', 'lbAuthorizer', 'lbFeeSink', 'programAddress', 'lbFeeReceiver']) {
    if (a[key] != null) {
      console.error(`Refusing sync: fabricated non-null ${key} while mainnetDeployExecuted=false`)
      process.exit(1)
    }
  }
}

const q = (v) => (v == null ? 'null as string | null' : `'${v}' as string | null`)

const body = `/**
 * Canonical Liquidity Building deployment binding for the web app.
 * Mirrors deployments/liquidity-building/chain-56/deployed-addresses.v1.json.
 * Generated by deployments/liquidity-building/sync-frontend-binding.mjs — do not hand-edit addresses.
 */

export const LB_CHAIN_ID = 56 as const

export const LB_MELEGA_AMM = {
  factory: '${a.melegaFactory}',
  router: '${a.melegaRouter}',
} as const

/**
 * Production LB program bindings.
 * Synced from deployments/liquidity-building/chain-56/deployed-addresses.v1.json after verified mainnet deploys.
 */
export const LB_CANONICAL_DEPLOYED_ADDRESSES = {
  lbFactory: ${q(a.lbFactory)},
  lbAuthorizer: ${q(a.lbAuthorizer)},
  lbFeeSink: ${q(a.lbFeeSink)},
  lbFeeReceiver: ${q(a.lbFeeReceiver)},
  lbProgramImplementation: ${q(a.lbProgramImplementation)},
  lbExecutionMathLibrary: ${q(a.lbExecutionMathLibrary)},
  programAddress: ${q(a.programAddress)},
} as const

export type LbCanonicalDeployedAddresses = {
  lbFactory: string | null
  lbAuthorizer: string | null
  lbFeeSink: string | null
  programAddress: string | null
}

export function readCanonicalLbAddresses(): LbCanonicalDeployedAddresses {
  return {
    lbFactory: LB_CANONICAL_DEPLOYED_ADDRESSES.lbFactory,
    lbAuthorizer: LB_CANONICAL_DEPLOYED_ADDRESSES.lbAuthorizer,
    lbFeeSink: LB_CANONICAL_DEPLOYED_ADDRESSES.lbFeeSink,
    programAddress: LB_CANONICAL_DEPLOYED_ADDRESSES.programAddress,
  }
}

export function lbCoreContractsBound(addrs: LbCanonicalDeployedAddresses = readCanonicalLbAddresses()): boolean {
  return Boolean(addrs.lbFactory && addrs.lbAuthorizer && addrs.lbFeeSink)
}
`

fs.writeFileSync(TARGET, body)
console.log(JSON.stringify({ synced: true, mainnetDeployExecuted: doc.mainnetDeployExecuted, target: TARGET }, null, 2))
